def martin_ost_a():
    S = "Martingales_and_Optional_Stopping"
    p = ExamPDF("Martingales and Optional Stopping Theorem  -  Answer Key 1")
    p.add_page()

    # ── Q1 ──
    p.AH("Q1  Solution")
    p.AL("a)  S(n) is a martingale:")
    p.txt("E[S(n+1) | F_n] = E[S(n) + X_{n+1} | F_n]\n"
          "                = E[S(n) | F_n] + E[X_{n+1} | F_n]\n"
          "                = S(n) + E[X_{n+1}]    (S(n) is F_n-measurable;\n"
          "                                         X_{n+1} is independent of F_n)\n"
          "                = S(n) + 0\n"
          "                = S(n)  (OK)\n\n"
          "So S(n) satisfies E[S(n+1)|F_n] = S(n): it is a martingale.")

    p.AL("b)  M(n) = S(n)^2 - n is a martingale:")
    p.txt("Compute E[M(n+1) | F_n]:\n\n"
          "  E[S(n+1)^2 - (n+1) | F_n]\n"
          "= E[(S(n) + X_{n+1})^2 | F_n] - (n+1)\n"
          "= E[S(n)^2 + 2*S(n)*X_{n+1} + X_{n+1}^2 | F_n] - (n+1)\n"
          "= S(n)^2 + 2*S(n)*E[X_{n+1}] + E[X_{n+1}^2] - (n+1)\n"
          "  [using S(n) is F_n-measurable, X_{n+1} independent of F_n]\n"
          "= S(n)^2 + 2*S(n)*0 + 1 - (n+1)\n"
          "= S(n)^2 - n\n"
          "= M(n)  (OK)\n\n"
          "So M(n) = S(n)^2 - n is a martingale.")

    p.AL("c)  Classification when E[X_i] = c > 0:")
    p.txt("E[S(n+1) | F_n] = S(n) + E[X_{n+1}] = S(n) + c > S(n).\n\n"
          "Since expected future value EXCEEDS current value, S(n) is a SUBMARTINGALE.\n"
          "(The walk has upward drift -- on average it grows.)\n\n"
          "For -S(n): E[-S(n+1) | F_n] = -S(n) - c < -S(n).\n"
          "So -S(n) is a SUPERMARTINGALE.\n"
          "(Flipping the sign reverses the inequality.)")

    p.sep()

    # ── Q2 ──
    p.AH("Q2  Solution")
    p.AL("a)  Winning probability h(k) = P(reach N before 0):")
    p.txt("Apply OST to the martingale S(n). Since T is bounded (T <= N^2 can\n"
          "be shown), the conditions are satisfied:\n\n"
          "  E[S(T)] = E[S(0)] = k\n\n"
          "At stopping time T, S(T) = N (with probability h(k)) or S(T) = 0\n"
          "(with probability 1 - h(k)). So:\n\n"
          "  E[S(T)] = N * h(k) + 0 * (1 - h(k)) = N * h(k)\n\n"
          "Setting equal:\n"
          "  N * h(k) = k\n"
          "  h(k) = k / N\n\n"
          "The probability of reaching N before 0 is exactly k/N -- proportional\n"
          "to the starting position. This is the classic Gambler's Ruin result\n"
          "for a symmetric random walk.")

    p.AL("b)  Expected absorption time E[T | S(0) = k]:")
    p.txt("Apply OST to the martingale M(n) = S(n)^2 - n:\n\n"
          "  E[M(T)] = E[M(0)] = k^2 - 0 = k^2\n\n"
          "At time T:\n"
          "  M(T) = S(T)^2 - T\n\n"
          "  E[M(T)] = E[S(T)^2] - E[T]\n"
          "           = [N^2 * h(k) + 0^2 * (1-h(k))] - E[T]\n"
          "           = N^2 * (k/N) - E[T]\n"
          "           = N*k - E[T]\n\n"
          "Setting equal to k^2:\n"
          "  N*k - E[T] = k^2\n"
          "  E[T] = N*k - k^2 = k*(N - k)")

    p.AL("c)  Numerical answer for N=4, k=1:")
    p.txt("  h(1) = 1/N = 1/4 = 0.25\n\n"
          "There is only a 25% chance of reaching the goal (N=4)\n"
          "before going broke, starting just one step away from ruin.\n\n"
          "  E[T] = k*(N-k) = 1*(4-1) = 3 steps\n\n"
          "The game lasts an average of 3 steps. This seems short, but makes\n"
          "sense: 75% of the time the gambler goes broke quickly (loses in 1 step\n"
          "with prob 1/2, or in a few steps), and only 25% of the time does the\n"
          "game last long enough to reach 4.")

    p.sep()

    # ── Q3 ──
    p.AH("Q3  Solution")
    p.AL("a)  T* is a valid stopping time:")
    p.txt("T* = min{n >= 1 : S(n) > 0}.\n\n"
          "The event {T* = n} means:\n"
          "  S(1) <= 0, S(2) <= 0, ..., S(n-1) <= 0, S(n) > 0.\n\n"
          "Each of these conditions depends only on X_1, ..., X_n (not on future\n"
          "steps), so {T* = n} is determined by F_n. Therefore T* is a valid\n"
          "stopping time: the decision to stop is based only on past outcomes.")

    p.AL("b)  Value of S at stopping:")
    p.txt("Each step X_i is either +1 or -1. So S(n) always changes by exactly 1\n"
          "at each step. The first time S(n) becomes positive (> 0), starting from\n"
          "S(0) = 0, the walk must reach +1 (it cannot jump from 0 or below to +2\n"
          "or higher in a single step of size +1).\n\n"
          "Therefore: S(T*) = +1 whenever T* < inf.\n\n"
          "The gambler always stops exactly 1 unit ahead when they stop.")

    p.AL("c)  Which OST condition fails? E[T*] = infinity:")
    p.txt("We have E[S(T*)] = 1 (since S(T*)=1 always when finite), but E[S(0)]=0.\n"
          "This contradicts OST unless one of its conditions fails.\n\n"
          "Condition (ii) requires E[T*] < inf with bounded increments.\n"
          "Increments are bounded (|X_i| = 1), so the issue must be E[T*] = inf.\n\n"
          "Why E[T*] = inf for symmetric random walk:\n"
          "  The symmetric random walk on Z is RECURRENT: it visits every integer\n"
          "  infinitely often with probability 1. In particular, it returns to 0\n"
          "  infinitely often.\n\n"
          "  The expected return time to state 0 for a symmetric random walk is\n"
          "  INFINITE (the walk is null-recurrent). Since T* is related to the\n"
          "  return time, E[T*] = inf.\n\n"
          "Conclusion: OST does NOT apply here because E[T*] = inf.\n"
          "The 'Stop When You're Ahead' strategy beats the fair game in expectation\n"
          "of the final amount -- but only by waiting an infinitely long time on\n"
          "average. No practical advantage exists.")
    p.save(ap(S, "Question_Set_1_Answers.pdf"))


