def wald_demoivre_a():
    S = "Walds_Equality_and_De_Moivre_Martingale"
    p = ExamPDF("Wald's Equality and De Moivre's Martingale  -  Answer Key 1")
    p.add_page()

    # ── Q1 ──
    p.AH("Q1  Solution")
    p.AL("a)  E[X_i] and Var[X_i] for a fair die:")
    p.txt("  E[X] = (1+2+3+4+5+6)/6 = 21/6 = 7/2 = 3.5\n\n"
          "  E[X^2] = (1+4+9+16+25+36)/6 = 91/6 ~ 15.167\n\n"
          "  Var[X] = E[X^2] - (E[X])^2 = 91/6 - (7/2)^2\n"
          "         = 91/6 - 49/4\n"
          "         = 182/12 - 147/12\n"
          "         = 35/12 ~ 2.917")

    p.AL("b)  Approximate E[T] via Wald's Equality:")
    p.txt("Wald's Equality: E[S(T)] = E[X] * E[T]\n\n"
          "Since S(T) >= 100 and the overshoot is small relative to 100,\n"
          "we approximate E[S(T)] ~ 100. Therefore:\n\n"
          "  100 ~ E[X] * E[T] = (7/2) * E[T]\n"
          "  E[T] ~ 100 / (7/2) = 200/7 ~ 28.57 rolls\n\n"
          "You need approximately 28-29 die rolls to reach a sum of 100.")

    p.AL("c)  Probability of hitting exactly 100:")
    p.txt("By renewal theory (the renewal process where S(n) is the position and\n"
          "100 is a renewal target), the long-run probability of the sum passing\n"
          "through any specific integer m is approximately 1/E[X] = 2/7.\n\n"
          "  P(S(n) = 100 for some n) ~ 1/E[X] = 2/7 ~ 0.286\n\n"
          "About a 28.6% chance of landing exactly on 100 at some step.\n"
          "The remaining ~71.4% of the time, the sum jumps over 100.\n"
          "(For example, at sum 95 you roll a 6 and land on 101.)")

    p.sep()

    # ── Q2 ──
    p.AH("Q2  Solution")
    p.AL("a)  Verify r = q/p and E[r^{X_{n+1}}] = 1:")
    p.txt("  p = 3/5, q = 2/5, r = q/p = (2/5)/(3/5) = 2/3\n\n"
          "Verify E[r^{X_{n+1}}] = 1:\n"
          "  E[r^{X_{n+1}}] = p * r^{+1} + q * r^{-1}\n"
          "                 = (3/5) * (2/3) + (2/5) * (3/2)\n"
          "                 = 2/5 + 3/5\n"
          "                 = 1  (OK)\n\n"
          "Therefore:\n"
          "  E[M(n+1) | F_n] = M(n) * E[r^{X_{n+1}}] = M(n) * 1 = M(n)\n"
          "M(n) = r^{S(n)} = (2/3)^{S(n)} is a martingale.")

    p.AL("b)  Gambler's Ruin probability h via OST on De Moivre's martingale:")
    p.txt("Apply OST to M(n) = (2/3)^{S(n)} with T = first hit of {0, 6},\n"
          "starting at S(0) = k = 2:\n\n"
          "  E[M(T)] = E[M(0)] = r^k = (2/3)^2 = 4/9\n\n"
          "At stopping time T:\n"
          "  M(T) = r^6 = (2/3)^6 = 64/729  with probability h (reach N=6)\n"
          "  M(T) = r^0 = 1                 with probability 1-h (reach 0)\n\n"
          "Setting up the equation:\n"
          "  (64/729) * h + 1 * (1 - h) = 4/9\n"
          "  (64/729) * h + 1 - h = 4/9\n"
          "  h * (64/729 - 1) = 4/9 - 1\n"
          "  h * (64/729 - 729/729) = 4/9 - 9/9\n"
          "  h * (-665/729) = -5/9\n"
          "  h = (5/9) / (665/729)\n"
          "    = (5/9) * (729/665)\n"
          "    = 5 * 81 / 665\n"
          "    = 405 / 665\n"
          "    = 81/133 ~ 0.609")

    p.AL("c)  Comparison to symmetric walk and P(ruin):")
    p.txt("Symmetric walk (p = 1/2): h_sym = k/N = 2/6 = 1/3 ~ 0.333\n"
          "Biased walk   (p = 3/5): h = 81/133 ~ 0.609\n\n"
          "With upward bias (p = 3/5 > 1/2), the probability of reaching the\n"
          "goal INCREASES significantly: from 33.3% to 60.9%.\n\n"
          "Intuition: with drift +1 on average per step (E[X] = 2p-1 = 0.2 > 0),\n"
          "the walk tends to move toward higher states, making N=6 more reachable\n"
          "than ruin at 0 from position k=2.\n\n"
          "  P(ruin before goal) = 1 - h = 1 - 81/133 = 52/133 ~ 0.391")

    p.sep()

    # ── Q3 ──
    p.AH("Q3  Solution")
    p.AL("a)  Risk-neutral probability p*:")
    p.txt("Write S(1) = S(0) * Y_1 where Y_1 = u=1.1 with prob p or d=0.9 with prob 1-p.\n\n"
          "For S(n) to be a martingale (E[S(1)] = S(0)):\n"
          "  E[S(1)] = S(0) * E[Y_1] = S(0) * (p*u + (1-p)*d) = S(0)\n"
          "  => p*u + (1-p)*d = 1\n"
          "  => p*1.1 + (1-p)*0.9 = 1\n"
          "  => 0.9 + p*(1.1 - 0.9) = 1\n"
          "  => 0.9 + 0.2*p = 1\n"
          "  => p* = 0.1/0.2 = 0.5\n\n"
          "The risk-neutral probability is p* = 1/2 (equal weight to up and down).\n"
          "This makes sense: when p*u + (1-p*)d = 1, the expected return is zero,\n"
          "meaning the asset has no drift under this measure.")

    p.AL("b)  S(n) is a martingale under p* = 1/2:")
    p.txt("Write S(n+1) = S(n) * Y_{n+1} where Y_{n+1} = 1.1 (prob 1/2) or 0.9 (prob 1/2),\n"
          "and Y_{n+1} is independent of F_n.\n\n"
          "  E[S(n+1) | F_n] = S(n) * E[Y_{n+1} | F_n]\n"
          "                  = S(n) * E[Y_{n+1}]  (by independence)\n"
          "                  = S(n) * (0.5*1.1 + 0.5*0.9)\n"
          "                  = S(n) * (0.55 + 0.45)\n"
          "                  = S(n) * 1.0\n"
          "                  = S(n)  (OK)\n\n"
          "So S(n) is indeed a martingale under p* = 1/2.")

    p.AL("c)  Jensen's Inequality and real-world measure:")
    p.txt("Under the real-world measure with p > p* = 1/2 (upward drift):\n\n"
          "  E[Y] = p*1.1 + (1-p)*0.9 = 0.9 + 0.2*p > 0.9 + 0.2*0.5 = 1\n"
          "  (since p > 0.5 implies 0.2*p > 0.1)\n\n"
          "So E[Y] > 1 under the real-world measure with p > 1/2.\n\n"
          "  E[S(n+1) | F_n] = S(n) * E[Y] > S(n)\n\n"
          "=> S(n) is a SUBMARTINGALE under the real-world measure with upward drift.\n\n"
          "Jensen's connection:\n"
          "The multiplicative model S(n) = S(0) * Y_1 * ... * Y_n can be written as\n"
          "S(n) = S(0) * e^{Z_1 + ... + Z_n} where Z_i = log(Y_i). By Jensen's\n"
          "inequality with the convex function f(x) = e^x:\n"
          "  E[S(n)] = S(0)*E[e^{Z_1+...+Z_n}] >= S(0)*e^{E[Z_1+...+Z_n]}\n\n"
          "Since E[Z_i] = p*log(1.1) + (1-p)*log(0.9) > 0 when p > 1/2 (more up\n"
          "moves on average, and log(1.1) > |log(0.9)| is not exactly true but the\n"
          "principle holds for E[Y]>1), the asset price grows on average.\n"
          "This confirms E[S(n)] > S(0) under upward drift, i.e. S(n) is a submartingale.")
